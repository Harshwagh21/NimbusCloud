// Package file owns persistence for file metadata and upload sessions.
// Upload rules live in the service; this package only runs sqlc queries.
package file

import (
	"context"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgxpool"

	dbgen "github.com/Harshwagh21/NimbusCloud/db/generated"
)

// Querier is the method set a transaction exposes. WithinTx's callback takes this type so
// the service can be tested with a fake instead of *Repository.
type Querier interface {
	Create(ctx context.Context, params CreateParams) (dbgen.File, error)
	GetByID(ctx context.Context, id, ownerID uuid.UUID) (dbgen.File, error)
	MarkReady(ctx context.Context, id, ownerID uuid.UUID, mimeType string) (dbgen.File, error)
	CreateUploadSession(ctx context.Context, params CreateUploadSessionParams) (dbgen.UploadSession, error)
	GetUploadSessionByID(ctx context.Context, id, userID uuid.UUID) (dbgen.UploadSession, error)
	CompleteUploadSession(ctx context.Context, id, userID uuid.UUID) (dbgen.UploadSession, error)
	AddStorageUsed(ctx context.Context, userID uuid.UUID, bytes int64) (int64, error)
}

// Repository is a thin wrapper over sqlc. No business rules live here.
type Repository struct {
	pool    *pgxpool.Pool
	queries *dbgen.Queries
}

func NewRepository(pool *pgxpool.Pool) *Repository {
	return &Repository{pool: pool, queries: dbgen.New(pool)}
}

// CreateParams is the data needed to insert a file row. ID is generated by the caller
// because the storage key contains it.
type CreateParams struct {
	ID         uuid.UUID
	OwnerID    uuid.UUID
	FolderID   *uuid.UUID
	Name       string
	StorageKey string
	MimeType   string
	Size       int64
	Checksum   *string
	Status     dbgen.FileStatus
}

func (r *Repository) Create(ctx context.Context, params CreateParams) (dbgen.File, error) {
	return r.queries.CreateFile(ctx, dbgen.CreateFileParams{
		ID:         params.ID,
		OwnerID:    params.OwnerID,
		FolderID:   params.FolderID,
		Name:       params.Name,
		StorageKey: params.StorageKey,
		MimeType:   params.MimeType,
		Size:       params.Size,
		Checksum:   params.Checksum,
		Status:     params.Status,
	})
}

func (r *Repository) GetByID(ctx context.Context, id, ownerID uuid.UUID) (dbgen.File, error) {
	return r.queries.GetFileByID(ctx, dbgen.GetFileByIDParams{
		ID:      id,
		OwnerID: ownerID,
	})
}

// MarkReady flips UPLOADING to READY. pgx.ErrNoRows means the file is not this owner's
// or is no longer UPLOADING.
func (r *Repository) MarkReady(ctx context.Context, id, ownerID uuid.UUID, mimeType string) (dbgen.File, error) {
	return r.queries.MarkFileReady(ctx, dbgen.MarkFileReadyParams{ID: id, OwnerID: ownerID, MimeType: mimeType})
}

func (r *Repository) ListByFolder(ctx context.Context, ownerID uuid.UUID, folderID *uuid.UUID) ([]dbgen.File, error) {
	return r.queries.ListFilesByFolder(ctx, dbgen.ListFilesByFolderParams{
		OwnerID:  ownerID,
		FolderID: folderID,
	})
}

func (r *Repository) SoftDelete(ctx context.Context, id, ownerID uuid.UUID) (dbgen.File, error) {
	return r.queries.SoftDeleteFile(ctx, dbgen.SoftDeleteFileParams{
		ID:      id,
		OwnerID: ownerID,
	})
}

// CreateUploadSessionParams is the data needed to track a direct-to-storage upload.
type CreateUploadSessionParams struct {
	UserID        uuid.UUID
	FileID        uuid.UUID
	UploadID      *string
	DeclaredSize  int64
	ReservedBytes int64
	PartsUploaded int32
	Status        dbgen.UploadSessionStatus
	ExpiresAt     time.Time
}

func (r *Repository) CreateUploadSession(ctx context.Context, params CreateUploadSessionParams) (dbgen.UploadSession, error) {
	return r.queries.CreateUploadSession(ctx, dbgen.CreateUploadSessionParams{
		UserID:        params.UserID,
		FileID:        params.FileID,
		UploadID:      params.UploadID,
		DeclaredSize:  params.DeclaredSize,
		ReservedBytes: params.ReservedBytes,
		PartsUploaded: params.PartsUploaded,
		Status:        params.Status,
		ExpiresAt:     params.ExpiresAt,
	})
}

func (r *Repository) GetUploadSessionByID(ctx context.Context, id, userID uuid.UUID) (dbgen.UploadSession, error) {
	return r.queries.GetUploadSessionByID(ctx, dbgen.GetUploadSessionByIDParams{
		ID:     id,
		UserID: userID,
	})
}

// CompleteUploadSession flips ACTIVE to COMPLETED. pgx.ErrNoRows means not found, not
// owned, or already finished.
func (r *Repository) CompleteUploadSession(ctx context.Context, id, userID uuid.UUID) (dbgen.UploadSession, error) {
	return r.queries.CompleteUploadSession(ctx, dbgen.CompleteUploadSessionParams{ID: id, UserID: userID})
}

// AddStorageUsed charges bytes to the user and returns the new total. pgx.ErrNoRows means
// the charge would exceed storage_limit and nothing changed.
// shortcut: STORAGE_MODE=premium is still capped at storage_limit; Phase 11 adds modes and reservations.
func (r *Repository) AddStorageUsed(ctx context.Context, userID uuid.UUID, bytes int64) (int64, error) {
	return r.queries.AddStorageUsed(ctx, dbgen.AddStorageUsedParams{ID: userID, Bytes: bytes})
}

// WithinTx runs fn against this repository bound to one transaction: every write in fn
// commits together or not at all.
func (r *Repository) WithinTx(ctx context.Context, fn func(Querier) error) error {
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(context.Background()) }()

	if err := fn(&Repository{queries: r.queries.WithTx(tx)}); err != nil {
		return err
	}
	return tx.Commit(ctx)
}

var _ Querier = (*Repository)(nil)
